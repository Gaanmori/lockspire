/// Los sitios en memoria: [icons] por host; el resto no tiene ícono.
/// Registra a qué hosts se les pidió, para comprobar qué sale a la red.
class FakeSiteIconFetcher implements SiteIconFetcherPort {
  final icons = <String, Uint8List>{};
  final asked = <String>[];

  @override
  Future<Uint8List?> fetchPng(String host) async {
    asked.add(host);
    return icons[host];
  }
}
